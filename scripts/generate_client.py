"""Writes src/contracts/openapi.json and the typed client grc_client from the API.

uv run python scripts/generate_client.py          # refresh snapshot and client
uv run python scripts/generate_client.py --check  # fail when snapshot or client drift from the code
"""

import json
import keyword
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "src/contracts/openapi.json"
PKG = ROOT / "src/contracts/grc_client"


def load_spec() -> dict[str, Any]:
    sys.path.insert(0, str(ROOT / "src/api"))
    from grc_api.main import create_app

    return create_app(run_lifespan=False).openapi()


def py_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        parts = [py_type(s) for s in schema["anyOf"]]
        return " | ".join(dict.fromkeys(parts))
    t = schema.get("type")
    if t == "string":
        return "str"
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    if t == "null":
        return "None"
    if t == "array":
        return f"list[{py_type(schema.get('items', {}))}]"
    if t == "object":
        add = schema.get("additionalProperties")
        if isinstance(add, dict) and add:
            return f"dict[str, {py_type(add)}]"
        return "dict[str, Any]"
    return "Any"


def models(spec: dict[str, Any]) -> str:
    out = [
        '"""Models of the API contract (generated by scripts/generate_client.py – do not edit)."""',
        "",
        "from typing import Any, TypedDict",
        "",
    ]
    schemas = spec.get("components", {}).get("schemas", {})
    for name in sorted(schemas):
        s = schemas[name]
        if s.get("type") != "object" and "properties" not in s:
            out += ["", f"{name} = Any", ""]
            continue
        # quoted types: models may refer to models defined further down
        fields = ", ".join(f'"{k}": "{py_type(v)}"' for k, v in s.get("properties", {}).items())
        out += ["", f'{name} = TypedDict("{name}", {{{fields}}}, total=False)', ""]
    return "\n".join(out).rstrip() + "\n"


def method_name(op_id: str) -> str:
    name = re.sub(r"\W", "_", op_id)
    return name + "_" if keyword.iskeyword(name) else name


def client(spec: dict[str, Any]) -> str:
    lines = [
        '"""Typed client of the GRC Studio API (generated by scripts/generate_client.py – do not edit)."""',
        "",
        "from typing import Any, cast",
        "",
        "import httpx",
        "",
        "from grc_client.models import *  # noqa: F403",
        "from typing import Any as _Any",
        "",
        "",
        "class ApiError(Exception):",
        '    """A problem document (RFC 9457) answered by the API."""',
        "",
        "    def __init__(self, status: int, problem: dict[str, Any]) -> None:",
        "        super().__init__(f\"{status} {problem.get('code', '')}: {problem.get('detail', '')}\")",
        "        self.status = status",
        "        self.problem = problem",
        '        self.code = str(problem.get("code", "error"))',
        "",
        "",
        "class GrcClient:",
        '    """One instance per incoming request: carries the user\'s session cookie and CSRF token."""',
        "",
        '    def __init__(self, http: httpx.AsyncClient, csrf_token: str = "") -> None:',
        "        self.http = http",
        "        self.csrf_token = csrf_token",
        "        self.last_response: httpx.Response | None = None",
        "",
        "    async def _call(self, method: str, path: str, *, json: Any = None, params: dict[str, Any] | None = None, if_match: str | None = None) -> Any:",
        "        headers: dict[str, str] = {}",
        '        if method != "GET" and self.csrf_token:',
        '            headers["X-CSRF-Token"] = self.csrf_token',
        "        if if_match is not None:",
        '            headers["If-Match"] = if_match',
        "        clean = {k: v for k, v in (params or {}).items() if v is not None}",
        "        r = await self.http.request(method, path, json=json, params=clean or None, headers=headers)",
        "        self.last_response = r",
        "        if r.status_code >= 400:",
        "            try:",
        "                problem = r.json()",
        "            except ValueError:",
        '                problem = {"code": "error", "detail": r.text}',
        "            raise ApiError(r.status_code, problem)",
        "        if r.status_code == 204 or not r.content:",
        "            return None",
        "        return r.json()",
    ]
    for path, ops in sorted(spec["paths"].items()):
        for method, op in sorted(ops.items()):
            op_id = op["operationId"]
            params = op.get("parameters", [])
            args: list[str] = []
            pathargs = [p["name"] for p in params if p["in"] == "path"]
            query = [p for p in params if p["in"] == "query"]
            has_if_match = any(
                p["in"] == "header" and p["name"].lower() == "if-match" for p in params
            )
            for n in pathargs:
                args.append(f"{n}: str")
            body = (
                op.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            if body is not None:
                args.append(f"body: {py_type(body)}")
            for q in query:
                args.append(f"{q['name']}: {py_type(q.get('schema', {}))} | None = None")
            if has_if_match:
                args.append("if_match: str | None = None")
            ok = next((c for c in ("200", "201") if c in op.get("responses", {})), None)
            ret = "None"
            if ok:
                sch = (
                    op["responses"][ok].get("content", {}).get("application/json", {}).get("schema")
                )
                ret = py_type(sch) if sch else "Any"
            fpath = 'f"' + path + '"' if pathargs else f'"{path}"'
            call = f'await self._call("{method.upper()}", {fpath}'
            if body is not None:
                call += ", json=body"
            if query:
                call += ", params={" + ", ".join(f'"{q["name"]}": {q["name"]}' for q in query) + "}"
            if has_if_match:
                call += ", if_match=if_match"
            call += ")"
            perm = op.get("x-permission", "public")
            lines += [
                "",
                f"    async def {method_name(op_id)}(self{''.join(', ' + a for a in args)}) -> {ret}:",
            ]
            lines.append(f'        """{method.upper()} {path} (permission: {perm})."""')
            lines.append(
                f"        return cast({ret!r}, {call})" if ret != "None" else f"        {call}"
            )
    return "\n".join(lines) + "\n"


def formatted(code: str, name: str) -> str:
    """Generated code in the repository's ruff format, so that `--check` compares like with like."""
    out = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(PKG / name), "-"],
        input=code,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    return out.stdout


def render() -> dict[Path, str]:
    spec = load_spec()
    return {
        SNAPSHOT: json.dumps(spec, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
        PKG / "models.py": formatted(models(spec), "models.py"),
        PKG / "client.py": formatted(client(spec), "client.py"),
        PKG
        / "__init__.py": '"""Typed client of the GRC Studio API (generated)."""\n\nfrom grc_client.client import ApiError, GrcClient\n\n__all__ = ["ApiError", "GrcClient"]\n',
    }


def main() -> int:
    files = render()
    if "--check" in sys.argv:
        drift = [
            str(p.relative_to(ROOT))
            for p, c in files.items()
            if not p.exists() or p.read_text(encoding="utf-8") != c
        ]
        if drift:
            print("contract drift – run scripts/generate_client.py:", ", ".join(drift))
            return 1
        print("contract and client are up to date")
        return 0
    for p, c in files.items():
        p.write_text(c, encoding="utf-8")
    print("written:", ", ".join(str(p.relative_to(ROOT)) for p in files))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
